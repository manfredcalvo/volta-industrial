"""Export commit-authorship evidence for the FE Bar's "net-new work on top of the challenge" check.

Generated from `git log` plus the GitHub API (no hand-written claims): what the challenge template
import commit contained, then, per required component (Lakeflow pipeline, ML model, Genie agent)
and the new agent tool, every commit that built it with its author, email, GitHub login and size.
Writes fe_bar/evidence/authorship.md.

Usage: python scripts/export_authorship_evidence.py [--repo manfredcalvo/volta-industrial]
"""

import argparse
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
TEMPLATE_COMMIT = "dcd88c2"
COMPONENTS = {
    "Lakeflow pipeline (SDP)": ["transformation/*.sql"],
    "ML model (train, register, serve)": ["ml/"],
    "Genie agent": ["genie_space.json", "scripts/deploy_semantic_layer.py", "scripts/export_genie_evidence.py"],
    "Agent tool: live ML what-if": ["app/server/agent/tools/recommender.ts"],
}

ap = argparse.ArgumentParser()
ap.add_argument("--repo", default="manfredcalvo/volta-industrial")
ap.add_argument("--out", default="fe_bar/evidence/authorship.md")
args = ap.parse_args()


def git(*a: str) -> str:
    return subprocess.check_output(["git", *a], cwd=ROOT, text=True)


# GitHub login per commit sha (what the platform attributes each commit to).
logins = {}
for page in range(1, 4):
    batch = json.loads(subprocess.check_output(
        ["gh", "api", f"repos/{args.repo}/commits?per_page=100&page={page}"], text=True))
    logins.update({c["sha"]: (c.get("author") or {}).get("login", "unattributed") for c in batch})
    if len(batch) < 100:
        break

paths = [p for ps in COMPONENTS.values() for p in ps]
template_stat = git("show", "--stat", "--format=", TEMPLATE_COMMIT, "--",
                    "transformation/", "ml/", "genie_space.json", "app/server/agent/tools/").strip()

lines = [
    "# Commit authorship: what I built on top of the challenge template",
    "",
    f"Generated by `scripts/export_authorship_evidence.py` from `git log` and the GitHub API for "
    f"`github.com/{args.repo}`.",
    "",
    f"## What the template import contained (`{TEMPLATE_COMMIT}`, \"Import Volta Industrial workshop "
    "template (as provided)\")",
    "",
    "Restricted to `transformation/`, `ml/`, `genie_space.json` and `app/server/agent/tools/`. The template "
    "shipped only a README in `transformation/` and the Genie/MAS helper stubs; the pipeline SQL, `ml/`, "
    "the Genie definition and the what-if tool are **not** in it:",
    "",
    "```",
    template_stat or "(none of these paths)",
    "```",
    "",
]

for name, comp_paths in COMPONENTS.items():
    log = git("log", "--format=%H|%h|%ad|%an|%ae|%s", "--date=short", "--", *comp_paths).strip().splitlines()
    rows = [r.split("|", 5) for r in log if not r.split("|")[1].startswith(TEMPLATE_COMMIT)]
    numstat = git("log", "--numstat", "--format=", "--", *comp_paths).splitlines()
    added = sum(int(l.split("\t")[0]) for l in numstat if l and l.split("\t")[0].isdigit())
    lines += [f"## {name}", "", f"Paths: {', '.join(f'`{p}`' for p in comp_paths)} · lines added: {added:,}", "",
              "| commit | date | author | email | GitHub login | subject |", "|---|---|---|---|---|---|"]
    lines += [f"| `{h}` | {d} | {an} | {ae} | {logins.get(sha, 'not pushed')} | {s[:80]} |"
              for sha, h, d, an, ae, s in rows]
    lines.append("")

authors = sorted(set(git("log", "--format=%an <%ae>").strip().splitlines()))
lines += ["## All commits in the repository", "",
          f"{len(git('log', '--format=%h').split())} commits; distinct authors: " + "; ".join(f"`{a}`" for a in authors),
          f"GitHub logins: {', '.join(sorted(set(logins.values())))}.", ""]

out = ROOT / args.out
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size:,} chars)")
